// Transicoes reais do roteiro, sem DOM ou dependencias de producao.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ctx = { window: {} };
const modulePath = path.join(__dirname, '../js/interview.js');
if (fs.existsSync(modulePath)) vm.runInNewContext(fs.readFileSync(modulePath, 'utf8'), ctx);
assert.ok(ctx.window.Interview, 'o modulo deve oferecer as transicoes do modo entrevista');
const data = { sets: { demo: { projects: [{ id: 'P07' }], cases: [{ id: 'BC3' }] } } };
const original = { view: 'network', mode: 'public', country: 'Brasil', layers: ['fresh'], minScore: 85, selected: 'MAO', term: 'GRU', proj: 'P04', caseId: 'BC5', kpi: 'margin', calc: { capex: '123' } };
const copy = (v) => JSON.parse(JSON.stringify(v));
const state = copy(original), guide = ctx.window.Interview.create(state, data);

assert.equal(guide.start(), true, 'entra a partir de um estado publico');
assert.equal(state.mode, 'demo');
assert.equal(state.view, 'executive');
assert.equal(state.country, 'all');
assert.deepEqual(copy(state.layers), []);
assert.equal(state.minScore, 0);
assert.equal(guide.index, 0);
assert.equal(guide.previous(), false, 'na primeira etapa voltar nao altera o roteiro');
assert.equal(guide.start(), false, 'reentrar nao pode substituir o snapshot original');

assert.equal(guide.next(), true);
assert.equal(state.view, 'projects');
assert.equal(state.proj, 'P07', 'a etapa de projeto deve selecionar P07 mesmo com outro projeto previo');
assert.equal(guide.aligned(), true);
state.proj = 'P04';
assert.equal(guide.aligned(), false, 'selecionar outro projeto deve ser reconhecido como exploracao livre');
assert.equal(guide.select(guide.index), true);
assert.equal(state.proj, 'P07');
assert.equal(guide.next(), true);
assert.equal(state.view, 'risks');
assert.equal(guide.next(), true);
assert.equal(state.view, 'business');
assert.equal(state.caseId, 'BC3', 'a etapa financeira deve selecionar BC3 mesmo com outro caso previo');
assert.equal(guide.previous(), true);
assert.equal(state.view, 'risks');
assert.equal(guide.select(4), true, 'permite selecionar uma etapa sem percorrer as demais');
assert.equal(state.view, 'executive');
assert.equal(guide.next(), false, 'na ultima etapa avancar nao extrapola o roteiro');
assert.equal(guide.select(-1), false);
assert.equal(guide.select(5), false);
assert.equal(guide.select(1.5), false);
assert.equal(guide.index, 4);
state.view = 'network';
assert.equal(guide.aligned(), false, 'navegacao livre nao deve aparentar ser a tela do roteiro');
state.calc.capex = '999';
state.layers.push('ecommerce');
state.mode = 'internal';
assert.equal(guide.stop(), true);
assert.deepEqual(copy(state), original, 'sair restaura inclusive objetos aninhados, filtros e modo anterior');
assert.equal(guide.active, false);
assert.equal(guide.next(), false, 'navegar sem entrevista ativa nao altera o estado');
assert.equal(guide.stop(), false);

const withoutDemo = ctx.window.Interview.create(state, { sets: { demo: null } });
assert.equal(withoutDemo.available, false);
assert.equal(withoutDemo.start(), false, 'sem demo nao deve entrar nem modificar o estado');
assert.deepEqual(copy(state), original);
console.log('OK: entrevista (entrada, roteiro, alvos P07/BC3, limites, exploracao livre, snapshot e ausencia de demo).');
